<?php

namespace App\Services\Telemetry;

use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Str;

/**
 * Turns a frontend route id into the page key the `views` map is keyed by, and
 * refuses any id the frontend doesn't have.
 *
 * The panel is a client-side app, so the server never sees a page change. The
 * browser reports the route ids it navigated to instead. That makes the ids
 * input from a user, and a key is free text unless it is checked against
 * something the user can't write. The list here is TanStack Router's generated
 * route tree, which every build writes (`npm run build`, the Docker image and
 * the release archive all include it). Without the file, no views are counted.
 *
 * Only routes inside the signed-in app (`/_app`) count. The sign-in screens are
 * not usage.
 */
class PageKeys
{
    /** @param  ?string  $routeTree  the generated route tree; `resources/scripts/routeTree.gen.ts` unless a test says otherwise */
    public function __construct(private ?string $routeTree = null) {}

    public function for(string $routeId): ?string
    {
        if (! in_array($routeId, $this->routeIds(), true)) {
            return null;
        }

        return self::fromRouteId($routeId);
    }

    /**
     * `/_app/servers/$serverUuid/backups` becomes `servers.backups`. Pathless
     * layouts (`_dashboard`) and groups (`(login)`) drop out, and so does every
     * parameter: a key never carries a value from the URL, nor even which
     * parameter it was. A page that ends in a parameter is the detail page,
     * `show`, so `/_app/admin/nodes/$nodeId/` (`admin.nodes.show`) stays apart
     * from the list at `/_app/admin/_dashboard/nodes/` (`admin.nodes.index`).
     */
    public static function fromRouteId(string $routeId): ?string
    {
        if (! str_starts_with($routeId, '/_app/')) {
            return null;
        }

        $segments = [];
        $endsInParameter = false;

        foreach (explode('/', $routeId) as $segment) {
            if ($segment === '' || str_starts_with($segment, '_') || preg_match('/^\(.*\)$/', $segment) === 1) {
                continue;
            }

            $endsInParameter = str_starts_with($segment, '$');

            if (! $endsInParameter) {
                $segments[] = Str::kebab($segment);
            }
        }

        if ($endsInParameter) {
            $segments[] = 'show';
        } elseif (str_ends_with($routeId, '/')) {
            $segments[] = 'index';
        }

        $key = implode('.', $segments);

        return TelemetryKey::valid($key) ? $key : null;
    }

    /** @return list<string> */
    public function routeIds(): array
    {
        // Generated by the TanStack Router plugin; not committed.
        $path = $this->routeTree ?? resource_path('scripts/routeTree.gen.ts');

        if (! is_file($path)) {
            return [];
        }

        // Keyed by the file's mtime so a rebuild is picked up without a cache clear.
        return Cache::rememberForever('telemetry:page-routes:'.filemtime($path), function () use ($path) {
            $tree = (string) file_get_contents($path);

            if (preg_match('/export interface FileRoutesById \{(.*?)\n\}/s', $tree, $block) !== 1) {
                return [];
            }

            preg_match_all("/^\s*'(\/[^']*)':/m", $block[1], $ids);

            return array_values(array_unique($ids[1]));
        });
    }
}
